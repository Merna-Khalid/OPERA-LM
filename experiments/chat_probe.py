"""Pre-export quality gate for the chat model (run BEFORE section 10).

Loads the SFT checkpoint exactly the way sft.py's sample block and
export_hf.py do (same constructor flags from the arm name, eager path),
then runs a FIXED battery of conversations at temperature 0 (deterministic
auto-checks) and temperature 0.7 (eyeball samples), prints a scorecard +
full transcripts, and saves everything to <ckpt-dir>/probe.json (on Drive,
so the record survives the runtime).

  python experiments/chat_probe.py --arm fw_d3072_L2_r16 \\
      --ckpt-dir $OPERA_RUNS/fw_d3072_L2_r16_sft [--device cuda] [--strict]

Checks (pass/fail where an expectation is stated, reported otherwise):
  format    every reply stops (EOS) and never leaks a role marker '<|'
  copy      repeats an unusual sentence byte-for-byte
  memory    recalls facts planted 2+ turns back (the architecture claim)
  facts     one common-fact substring check (a 172M byte model is allowed
            to miss knowledge -- reported, not fatal, unless --strict)

The export round-trip check (config.json/safetensors load back and produce
identical logits) lives in export_hf.py itself and gates the push.
"""
import argparse
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..'))
sys.path.insert(0, HERE)

# (name, user text, expected lowercase substring or None)
SINGLE = [
    ('greet', 'Hi! Who are you?', None),
    ('short', 'Say OK and nothing else.', 'ok'),
    ('copy_exact', 'Repeat exactly: The quartz judge Axolotl vexes bright pens.',
     'the quartz judge axolotl vexes bright pens'),
    ('qa_capital', 'What is the capital of France?', 'paris'),
    ('qa_photo', 'What is photosynthesis? Explain it simply.', None),
    ('tips3', 'Give me three tips for staying focused while studying.', None),
]
# multi-turn: facts planted in turn 1, queried after filler turns
MEMORY = [
    ('Hi! My name is Merna and my bicycle is blue.', None),
    ('Tell me something interesting about the ocean.', None),
    ('What color is my bicycle?', 'blue'),
    ('What is my name?', 'merna'),
]
SAMPLED = ['Write a short story about a robot who learns to whistle.',
           'Translate "good morning" into French and use it in a sentence.',
           'List three planets and one fact about each.']


def load_sft_model(arm, ckpt_dir, device):
    """Same construction as sft.py's sample block / export_hf.py."""
    import torch
    import repr_study as rs
    from arm_utils import _model_kwargs
    from opera_lm import OperaSpinorFenwickTree
    rs.scale_arm(arm)
    _, _, d, nb = rs.ARMS[arm]
    layers = rs.LAYERS.get(arm, 2)
    kw = dict(vocab_size=259, d=d, nb=nb, num_layers=layers, pe_mode='none',
              fold_mode='left', rot_mode='free', fold_grade=rs.GRADE.get(arm),
              **_model_kwargs(rs.device_kernels(rs.ARCH.get(arm), 'cpu')))
    m = OperaSpinorFenwickTree(**kw)
    pts = [f for f in os.listdir(ckpt_dir)
           if f.endswith('.pt') and not f.endswith('_train_ckpt.pt')]
    assert len(pts) == 1, f'{ckpt_dir}: expected one final checkpoint, got {pts}'
    sd = torch.load(os.path.join(ckpt_dir, pts[0]), map_location='cpu',
                    weights_only=True)
    m.load_state_dict(sd.get('model', sd))      # final ckpts are raw state_dicts
    return m.to(device).eval(), pts[0]


def gen(model, prompt_ids, max_new=300, temperature=0.0, seed=0):
    """-> dict(text, n_bytes, stopped, sec). stream_generate yields once per
    generated byte plus one final flush, so bytes = yields - 1 and a count
    below max_new means generation hit EOS."""
    from opera_lm.chat import stream_generate
    t0 = time.time()
    n, text = 0, ''
    for text in stream_generate(model, prompt_ids, max_new=max_new,
                                temperature=temperature, top_p=0.9, seed=seed):
        n += 1
    n_bytes = max(0, n - 1)
    return dict(text=text, n_bytes=n_bytes, stopped=n_bytes < max_new,
                sec=time.time() - t0)


def check(model, name, user, expect, history, rows):
    from opera_lm.chat import format_prompt
    r = gen(model, format_prompt(history, user))
    leak = '<|' in r['text']
    ok_stop = r['stopped']
    ok_sub = (expect in r['text'].lower()) if expect else None
    verdict = (ok_stop and not leak) if expect is None else \
              bool(ok_stop and not leak and ok_sub)
    rows.append(dict(name=name, user=user, expect=expect,
                     passed=verdict, stopped=ok_stop, role_leak=leak,
                     substring=ok_sub, reply=r['text'], n_bytes=r['n_bytes'],
                     sec=r['sec']))
    print(f"  [{'PASS' if (expect and verdict) else 'FAIL' if expect else '----'}] "
          f"{name}: "
          f"{r['n_bytes']} bytes, {'EOS' if ok_stop else 'NO-STOP (hit cap)'}"
          f"{', ROLE LEAK' if leak else ''}, {r['sec']:.1f}s", flush=True)
    print(f"      U: {user}\n      A: {r['text']}", flush=True)
    return r['text']


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--arm', required=True)
    p.add_argument('--ckpt-dir', required=True, help='the *_sft run folder')
    p.add_argument('--device', default='cuda')
    p.add_argument('--max-new', type=int, default=300)
    p.add_argument('--strict', action='store_true',
                   help='exit 1 if any auto-checked probe fails '
                        '(default: report only -- model quality is a '
                        'judgment call before an export)')
    args = p.parse_args()

    model, ck = load_sft_model(args.arm, args.ckpt_dir, args.device)
    print(f'chat probe: {args.arm} (checkpoint {ck}) on {args.device}\n'
          f'== single prompts, temperature 0 ==', flush=True)
    rows = []
    for name, q, expect in SINGLE:
        check(model, name, q, expect, [], rows)

    print('\n== multi-turn memory conversation, temperature 0 ==', flush=True)
    history = []
    for i, (q, expect) in enumerate(MEMORY):
        a = check(model, f'memory_t{i + 1}', q, expect, history, rows)
        history.append((q, a))

    print('\n== sampled (temperature 0.7, seed 0) -- eyeball only ==', flush=True)
    sampled = []
    for q in SAMPLED:
        from opera_lm.chat import format_prompt
        r = gen(model, format_prompt([], q), max_new=args.max_new,
                temperature=0.7)
        sampled.append(dict(user=q, reply=r['text']))
        print(f"  >>> {q}\n  {r['text']}\n", flush=True)

    auto = [r for r in rows if r['expect'] is not None]
    n_pass = sum(bool(r['passed']) for r in auto)
    n_stop = sum(bool(r['stopped']) for r in rows)
    n_leak = sum(bool(r['role_leak']) for r in rows)
    bps = sum(r['n_bytes'] for r in rows) / max(1e-9, sum(r['sec'] for r in rows))
    print(f"SCORECARD: {n_pass}/{len(auto)} auto-checked probes passed; "
          f"{n_stop}/{len(rows)} replies stopped cleanly; "
          f"{n_leak} role leaks; decode {bps:.1f} bytes/s on {args.device}",
          flush=True)
    out = os.path.join(args.ckpt_dir, 'probe.json')
    json.dump(dict(arm=args.arm, ckpt=ck, device=args.device,
                   checks=rows, sampled=sampled,
                   summary=dict(auto_passed=n_pass, auto_total=len(auto),
                                stopped=n_stop, total=len(rows),
                                role_leaks=n_leak, bytes_per_sec=bps)),
              open(out, 'w'), indent=2)
    print(f'wrote {out}')
    if args.strict and n_pass < len(auto):
        sys.exit(1)


if __name__ == '__main__':
    main()
